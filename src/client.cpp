#include <cstdint>
#include <iomanip>
#include <iostream>
#include <winsock2.h>
#include <ws2tcpip.h>

#pragma comment(lib, "ws2_32.lib")

int main()
{
    WSADATA wsaData;
    WSAStartup(MAKEWORD(2, 2), &wsaData);

    SOCKET clientSocket = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);

    sockaddr_in serverAddr{};
    serverAddr.sin_family = AF_INET;
    serverAddr.sin_port = htons(8081);
    inet_pton(AF_INET, "127.0.0.1", &serverAddr.sin_addr);

    if (connect(clientSocket, (sockaddr*)&serverAddr, sizeof(serverAddr)) == 0)
    {
        // CG_ENTER test payload
        uint8_t hexPayload[] = {
            0x60, 0x00, 0x00, 0x00, 0x7D, 0x45, 0x06, 0x00, 0x10, 0x1A, 0xC8, 0x27, 0x07, 0xC5,
            0x72, 0x45, 0x1E, 0xCE, 0x21, 0xFD, 0xF4, 0xC9, 0xE1, 0x56, 0xE9, 0x1B, 0xB2, 0x96,
            0x43, 0x01, 0x8C, 0xEB, 0x8D, 0xA5, 0xFA, 0x56, 0xC6, 0x99, 0xC0, 0x73, 0x6E, 0x9D,
            0x15, 0x80, 0xEE, 0x71, 0x76, 0x5E, 0x99, 0xA7, 0xAD, 0x44, 0xD7, 0xDB, 0x5E, 0xCE,
            0x38, 0x16, 0x11, 0x9C, 0xA7, 0x3B, 0xB2, 0xB4, 0xD7, 0x9E, 0xE6, 0xE5, 0x50, 0x1B,
            0x56, 0x84, 0x85, 0xD9, 0x73, 0x79, 0xBA, 0x27, 0x45, 0x55, 0x68, 0xEE, 0x68, 0x96,
            0x9F, 0xF0, 0x56, 0xB5, 0x5D, 0x97, 0x52, 0x52, 0x3A, 0x8F, 0xEB, 0xDC};

        uint8_t buffer[1024] = {0};

        send(clientSocket, reinterpret_cast<const char*>(hexPayload), sizeof(hexPayload), 0);
        std::cout << "Sent " << sizeof(hexPayload) << " raw hex bytes!\n";

        int bytesReceived =
            recv(clientSocket, reinterpret_cast<char*>(buffer), sizeof(buffer) - 1, 0);

        for (int i = 0; i < bytesReceived; ++i)
        {
            std::cout << std::hex << std::setw(2) << std::setfill('0')
                      << static_cast<int>(buffer[i]) << " ";
        }
    }

    closesocket(clientSocket);
    WSACleanup();
    return 0;
}